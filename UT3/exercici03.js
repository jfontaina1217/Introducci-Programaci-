console.log(5 + 2); //Muestra la suma de los numeros
console.log("5" + 2); //El primer "numero" es un string, asi que se encadenan los caracteres
console.log(5 + 2 + "3"); //Primero se suma de izquierda a derecha, en el momento en el que llega al string, se encadena
console.log("5" + 2 + 3); //Como primero hay un string, a partir de ahí, todo se encadena